/**
 * Generates the cross-platform contract fixtures used by the Android (and later iOS) unit tests:
 *   npx tsx scripts/make-contract-fixtures.ts ../mesh/test-vectors/contract_v1/server_envelope.json
 * Everything is produced by the server's own helpers (src/testing/envelope.ts, src/crypto/*), so a client that verifies/decrypts
 * these files matches the server byte for byte. The private keys in the file are TEST KEYS ONLY.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { buildEnvelope, newTestDevice, signRequest } from '../src/testing/envelope';
import { generateKeyPair } from '../src/crypto/keys';
import { canonicalJson } from '../src/crypto/canonical';
import { envelopeSignedPart, deviceRequestMessage } from '../src/crypto/verify';
import { signBackendMessage, signReceipt } from '../src/crypto/receipts';
import { parseP256PrivateKey } from '../src/crypto/keys';

const out = process.argv[2] ?? '../mesh/test-vectors/contract_v1/server_envelope.json';
const enc = generateKeyPair();
const sign = generateKeyPair();
const signPriv = parseP256PrivateKey(sign.privateKey);
const device = newTestDevice();
const createdAt = new Date('2026-11-07T16:00:00.000Z');

const payload = {
  lat: 32.9857, lng: -96.7501, accuracy_m: 8.5, category: 'trapped', text: 'Trapped, 2 people, water rising é中 "quoted"',
  people_count: 2, trapped: true, water_rising: true,
};
const envelope = buildEnvelope({
  device, backendEncPublicKey: enc.publicKey, payload, createdAt, hopCount: 2, hopPath: ['E45B', 'B7C2'], inlinePublicKey: true,
});

const bmUnsigned = {
  id: '0192a7e0-5b1c-7000-8a00-0000000000b1', kind: 'status_update' as const, sos_id: envelope.id, checkin_id: null,
  body: { status: 'en_route', eta_minutes: 40, message: 'Help is on the way, ETA 40 min' },
  max_hops: 5, expires_at: '2026-11-07T22:00:00.000Z', created_at: '2026-11-07T16:30:00.000Z',
};
const backendMessage = signBackendMessage(signPriv, bmUnsigned);
const checkinMessage = signBackendMessage(signPriv, {
  id: '0192a7e0-5b1c-7000-8a00-0000000000b2', kind: 'checkin_request', sos_id: envelope.id, checkin_id: '0192a7f0-0000-7000-8000-0000000000c1',
  body: { message: 'Are you OK? Please reply.', deadline_at: '2026-11-07T16:45:00.000Z' },
  max_hops: 5, expires_at: '2026-11-07T22:00:00.000Z', created_at: '2026-11-07T16:30:00.000Z',
});
const receipt = signReceipt(signPriv, envelope.id, new Date('2026-11-07T16:05:00.000Z'));

device.id = '0192a000-0000-7000-8000-0000000000d1';
const reqBody = JSON.stringify({ envelopes: [envelope] });
const reqHeaders = signRequest(device, 'POST', '/v1/sos/batch', reqBody, new Date('2026-11-07T16:10:00.000Z'));

const canonicalCases = [
  { input: { b: 1, a: [true, null, 'x'], c: { z: 1.5, y: 0.00001, x: 1e-7 } }, output: '' },
  { input: { n: [1.0, 32.995, -96.745, 0.1, 1000, 1e21, 123456789012345680000, -0.5] }, output: '' },
  { input: { s: 'quote " back \\ nl \n tab \t ctl \u0001 uni é 中 😀' }, output: '' },
  { input: { 'é': 1, 'B': 2, 'a': 3, 'Z': 4 }, output: '' },
].map((c) => ({ input: c.input, output: canonicalJson(c.input) }));

const rawJson = canonicalCases.map((c) => ({ input_json: JSON.stringify(c.input), output: c.output }));

const doc = {
  description: 'Contract v1 fixtures generated by server/scripts/make-contract-fixtures.ts using the server test helpers. TEST KEYS ONLY.',
  backend: {
    encryption_public_key: enc.publicKey, encryption_private_key_pkcs8: enc.privateKey,
    signing_public_key: sign.publicKey, signing_private_key_pkcs8: sign.privateKey,
  },
  device: { public_key: device.publicKey, private_key_pkcs8: device.privateKey.export({ type: 'pkcs8', format: 'der' }).toString('base64'), id: device.id },
  now_for_validation: '2026-11-07T16:01:00.000Z',
  envelope,
  envelope_signed_part: envelopeSignedPart(envelope),
  expected_payload: payload,
  backend_message: backendMessage,
  backend_message_checkin: checkinMessage,
  delivered_receipt: receipt,
  request_signature: {
    method: 'POST', path: '/v1/sos/batch', body: reqBody, timestamp: reqHeaders['X-Timestamp'], signature: reqHeaders['X-Device-Signature'],
    signed_string: deviceRequestMessage('POST', '/v1/sos/batch', reqBody, reqHeaders['X-Timestamp']), empty_body_sha256: crypto.createHash('sha256').update('').digest('hex'),
  },
  canonical_json_cases: rawJson,
};
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(doc, null, 2) + '\n');
console.log('wrote', out);
